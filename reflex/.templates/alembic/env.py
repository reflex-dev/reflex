"""Alembic migration environment for a Reflex app.

Generated by ``reflex db init`` and owned by the app: edit it to change how
migrations are detected and applied. It loads the app so that every model is
registered and takes the database URL from ``db_url`` in rxconfig.py, so the
``sqlalchemy.url`` setting in alembic.ini is not used. Both the ``reflex db``
commands and the ``alembic`` command line run it.
"""

from __future__ import annotations

import logging
from logging.config import fileConfig
from typing import TYPE_CHECKING, Literal

import sqlalchemy
from alembic import context
from alembic.autogenerate.rewriter import Rewriter
from alembic.operations import ops
from reflex_base.config import get_config
from reflex_base.environment import environment

from reflex.model import ModelRegistry, get_engine
from reflex.utils.prerequisites import get_app

if TYPE_CHECKING:
    from alembic.autogenerate.api import AutogenContext
    from alembic.runtime.migration import MigrationContext

# this is the Alembic Config object, which provides
# access to the values within the .ini file in use.
config = context.config

# Apply the logging settings in alembic.ini when alembic runs on its own. Under
# the reflex CLI, or in an app that set up logging, handlers are already attached.
if (
    config.config_file_name is not None
    and not logging.getLogger("reflex").hasHandlers()
):
    fileConfig(config.config_file_name, disable_existing_loggers=False)

# Importing the app registers every model, so the metadata is complete.
get_app()
target_metadata = ModelRegistry.get_metadata()

writer = Rewriter()


@writer.rewrites(ops.AddColumnOp)
def add_column_with_server_default(
    context: MigrationContext, revision: str | None, op: ops.AddColumnOp
) -> ops.AddColumnOp:
    """Carry a column's Python-side default into the migration as a server default.

    Existing rows then get that value when the column is added, so a NOT NULL
    column can be added to a table that already holds data. A callable default
    is evaluated once, when the migration script is generated.

    Args:
        context: The migration context.
        revision: The revision being generated.
        op: The add-column operation to rewrite.

    Returns:
        The same operation, with ``server_default`` filled in.
    """
    default = op.column.default
    if default is not None and op.column.server_default is None:
        value = default.arg(None) if default.is_callable else default.arg
        op.column.server_default = sqlalchemy.DefaultClause(sqlalchemy.literal(value))
    return op


def process_revision_directives(
    context: MigrationContext,
    revision: str | None,
    directives: list[ops.MigrationScript],
) -> None:
    """Skip writing an autogenerated revision when the schema has not changed.

    Args:
        context: The migration context.
        revision: The revision being generated.
        directives: The revision scripts about to be written; cleared to skip.
    """
    autogenerate = getattr(config.cmd_opts, "autogenerate", False)
    if autogenerate and directives[0].upgrade_ops.is_empty():
        directives[:] = []
        return
    writer(context, revision, directives)


def render_item(
    type_: str, obj: object, autogen_context: AutogenContext
) -> Literal[False]:
    """Import sqlmodel in revision scripts that reference its column types.

    Args:
        type_: The kind of object being rendered, e.g. ``"type"`` or ``"column"``.
        obj: The object being rendered.
        autogen_context: The shared autogenerate context, which collects imports.

    Returns:
        False, so that alembic renders the object itself.
    """
    if type_ == "type" and type(obj).__module__.startswith("sqlmodel"):
        autogen_context.imports.add("import sqlmodel")
    return False


def configure(**kwargs: object) -> None:
    """Configure the migration context with the app's models and settings.

    Args:
        **kwargs: The connection or URL to migrate, and other context options.
    """
    context.configure(
        target_metadata=target_metadata,
        render_item=render_item,
        process_revision_directives=process_revision_directives,
        compare_type=False,
        include_schemas=environment.ALEMBIC_INCLUDE_SCHEMAS.get(),
        # Emulate ALTER TABLE on sqlite by rebuilding the table.
        render_as_batch=True,
        **kwargs,  # pyright: ignore [reportArgumentType]
    )


def run_migrations_offline() -> None:
    """Emit the migration SQL instead of running it (``alembic upgrade --sql``)."""
    configure(
        url=get_config().db_url,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run the migrations against the database from rxconfig.py."""
    with get_engine().connect() as connection:
        configure(connection=connection)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
