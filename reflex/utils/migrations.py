"""Thin wrappers over the alembic command line, used by `reflex db`.

The migration logic lives in alembic and in the env.py that `reflex db init`
writes from the template in `reflex/.templates/alembic`, so the `alembic`
command line works on a Reflex app exactly as `reflex db` does.
"""

from __future__ import annotations

import contextlib
import io
import logging
import shutil
from pathlib import Path
from typing import Literal

from reflex_base.environment import environment
from rich.markup import escape

from reflex.utils.prerequisites import get_and_validate_app, get_app

logger = logging.getLogger(__name__)

# The env.py that replaces the stock one after `alembic init`.
TEMPLATE_ENV_PY = Path(__file__).parent.parent / ".templates" / "alembic" / "env.py"

LEGACY_ENV_HINT = (
    "The migration environment was created by an earlier Reflex release and "
    "cannot load the app. Run [bold]reflex db init[/bold] to update env.py; "
    "existing revisions are kept."
)

UPDATED_ENV_MESSAGE = (
    "Updated env.py to load the app; the previous one is kept as {backup}."
)

# In the docstring of every env.py written from the template, since 0.11.0a1.
TEMPLATE_MARKER = "Generated by ``reflex db init``"

# The line of alembic's stock env.py that earlier releases never ran or edited.
LEGACY_MARKER = "target_metadata = None"

CUSTOM_ENV_HINT = (
    "alembic/env.py is not the Reflex template: move it aside and run "
    "[bold]reflex db init[/bold] to write the current template."
)

CUSTOM_ENV_WARNING = (
    "alembic/env.py is not the Reflex template, so what the template adds may be "
    "missing: the database URL from rxconfig.py, the models of the whole app, "
    "server defaults for added columns and warnings for dropped tables. Move it "
    "aside and run [bold]reflex db init[/bold] to adopt the template; existing "
    "revisions are kept."
)

EnvKind = Literal["template", "legacy", "custom"]

# True while env.py imports the app, when an import-time `migrate()` call would
# start a second alembic run inside the one already in progress.
_loading_app = False

# True while `run` executes an alembic command, so env.py can tell `reflex db`
# and `migrate()` apart from the `alembic` command line.
_in_run = False


def invoked_by_reflex() -> bool:
    """Whether the alembic command now running was started by `run`.

    Returns:
        True under `reflex db` and `migrate()`, False under the `alembic`
        command line.
    """
    return _in_run


def run(*args: str) -> None:
    """Run an alembic command line against the app's alembic.ini.

    Equivalent to ``alembic -c <ALEMBIC_CONFIG> <args>``, except that a failure
    raises ``alembic.util.exc.CommandError`` instead of exiting the process. A
    command issued while env.py imports the app, such as ``migrate()`` at module
    level, is skipped: alembic is already running and applies the scripts itself.

    Args:
        *args: The alembic command and its options, e.g. ``"upgrade", "head"``.
    """
    global _in_run

    if _loading_app:
        logger.debug(
            f"Skipping alembic {' '.join(args)}: an alembic run is loading the app."
        )
        return
    import alembic.config

    # An env.py other than the template may apply the logging settings in
    # alembic.ini, which replace the root handlers and disable every other logger.
    root = logging.getLogger()
    root_handlers, root_level = root.handlers[:], root.level
    enabled = [
        child
        for child in logging.Logger.manager.loggerDict.values()
        if isinstance(child, logging.Logger) and not child.disabled
    ]
    _in_run = True
    try:
        alembic.config.main(
            argv=[
                "--raiseerr",
                "--config",
                str(environment.ALEMBIC_CONFIG.get()),
                *args,
            ],
            prog="alembic",
        )
    finally:
        _in_run = False
        root.handlers[:] = root_handlers
        root.setLevel(root_level)
        for child in enabled:
            child.disabled = False


def autogenerate(message: str | None = None, write: bool = True) -> bool:
    """Compare the models with the database and write a revision if they differ.

    ``alembic check`` runs first, so that no empty revision is written even when
    env.py, unlike the template, does not skip one.

    Args:
        message: The message of the revision.
        write: Write the revision; otherwise only compare.

    Returns:
        True when the models and the database differ.
    """
    from alembic.util.exc import AutogenerateDiffsDetected

    try:
        run("--quiet", "check")
    except AutogenerateDiffsDetected:
        if write:
            run(
                "revision",
                "--autogenerate",
                *(("--message", message) if message else ()),
            )
        return True
    return False


def evaluate_pages() -> None:
    """Import the app and evaluate every page, rendering and writing nothing.

    Models that pages or plugin route hooks import lazily are registered only
    once the pages run. A plain skip-compile load evaluates just the routes the
    stateful-pages marker of an earlier run names; the dry run evaluates them all.
    The initial state is not serialized: without a frontend compile, the libraries
    that compiler plugins bundle are not registered for its components.
    """
    environment.REFLEX_SKIP_COMPILE.set(True)
    app, _ = get_and_validate_app()
    app._compile(dry_run=True, compile_initial_state=False)


def load_app(with_pages: bool = False) -> None:
    """Import the app for env.py, so that the models it declares are registered.

    The import may itself call ``migrate()`` at module level, before the app
    object exists; ``run`` skips the alembic command that would start then.

    Args:
        with_pages: Evaluate the pages too, for the models they import lazily.
            The ``reflex db`` commands do so before alembic runs; the ``alembic``
            command line leaves it to env.py.
    """
    from reflex.model import ModelRegistry

    global _loading_app

    _loading_app = True
    try:
        get_app()
        if with_pages:
            evaluate_pages()
    finally:
        _loading_app = False
    # Models registered since an earlier alembic run in this process, such as
    # those the pages import lazily, must reach this run's metadata.
    ModelRegistry._metadata = None


def init() -> None:
    """Run `alembic init` with its stock template, then install the reflex env.py.

    Without alembic's output: it names each template file even with --quiet, and
    its closing advice to edit the connection settings in alembic.ini does not
    apply, as env.py takes the database URL from rxconfig.py.
    """
    directory = environment.ALEMBIC_CONFIG.get().parent / "alembic"
    with contextlib.redirect_stdout(io.StringIO()):
        run("init", str(directory))
    install_env()


def install_env() -> Path:
    """Write the reflex env.py template into the script directory.

    Returns:
        The path of the written env.py.

    Raises:
        CommandError: If alembic.ini names no script directory or it is missing.
    """
    env_py = script_directory() / "env.py"
    shutil.copy(TEMPLATE_ENV_PY, env_py)
    return env_py


def script_directory() -> Path:
    """Locate the script directory named by alembic.ini.

    Returns:
        The directory holding env.py, script.py.mako and versions/.

    Raises:
        CommandError: If alembic.ini names no script directory or it is missing.
    """
    import alembic.config
    import alembic.script

    config = alembic.config.Config(environment.ALEMBIC_CONFIG.get())
    return Path(alembic.script.ScriptDirectory.from_config(config).dir)


def env_kind() -> EnvKind | None:
    """Tell where env.py comes from.

    Earlier Reflex releases ran `alembic init` with alembic's stock template and
    never executed the resulting env.py, which still reads
    ``target_metadata = None`` and connects to the placeholder URL in alembic.ini.
    An env.py with neither that line nor the template's marker was written or
    edited by hand, and alembic runs it as it is.

    Returns:
        ``"template"`` for the reflex template, ``"legacy"`` for the stock one,
        ``"custom"`` for any other, or None without an env.py.
    """
    from alembic.util.exc import CommandError

    try:
        env_py = script_directory() / "env.py"
    except CommandError:
        # Let the command that needs the directory report what is wrong with it.
        return None
    if not env_py.exists():
        return None
    source = env_py.read_text()
    if TEMPLATE_MARKER in source:
        return "template"
    return "legacy" if LEGACY_MARKER in source else "custom"


def check_env() -> EnvKind | None:
    """Tell where env.py comes from, warning once per process when it is custom.

    Returns:
        What ``env_kind`` returns.
    """
    kind = env_kind()
    if kind == "custom":
        logger.warning(CUSTOM_ENV_WARNING, extra={"dedupe": True, "rich": True})
    return kind


def is_legacy_env() -> bool:
    """Whether env.py predates the reflex template and cannot load the app.

    Returns:
        True if env.py is the stock alembic template.
    """
    return env_kind() == "legacy"


def update_legacy_env() -> Path | None:
    """Replace a stock env.py with the reflex template, keeping it as env.old.

    An earlier backup is kept too: the new one takes the first free name of
    env.old, env.old.1, env.old.2 and so on.

    Returns:
        Where the previous env.py went, or None when env.py is not the stock one.
    """
    if check_env() != "legacy":
        return None
    env_py = script_directory() / "env.py"
    backup = env_py.with_name("env.old")
    index = 0
    while backup.exists():
        index += 1
        backup = env_py.with_name(f"env.old.{index}")
    env_py.replace(backup)
    install_env()
    return backup


def describe_error(error: Exception) -> str:
    """Describe an alembic error with the reflex command that resolves it.

    Args:
        error: The ``CommandError`` alembic raised.

    Returns:
        The error message as rich markup, with a hint when the database is
        behind its scripts.
    """
    message = escape(str(error))
    if "Target database is not up to date." in message:
        message += " Run [bold]reflex db migrate[/bold] to update database."
    return message


def report_failure(error: Exception) -> None:
    """Log an exception other than a ``CommandError`` that an alembic run raised.

    It names the exception, with the fix when env.py is not the template, once
    per process: an import-time ``migrate()`` and the startup check fail alike.
    The traceback is logged at debug level.

    Args:
        error: The exception raised while alembic ran env.py.
    """
    message = escape(f"Alembic failed with {type(error).__name__}: {error}")
    if env_kind() == "custom":
        message = f"{message}\n{CUSTOM_ENV_HINT}"
    logger.error(message, extra={"dedupe": True, "rich": True})
    logger.debug("The alembic run failed.", exc_info=error)
