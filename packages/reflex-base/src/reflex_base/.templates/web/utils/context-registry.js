// React context objects shared by the generated context module and by every
// component that reads state. A provider and its consumers only connect when
// they hold the same context object, so the objects live here rather than in
// a module the compiler rewrites: Vite re-executes a rewritten module on hot
// update, and every module it imports along with it, but this module imports
// nothing that can change and is never re-executed.
import {
  createContext,
  useContext,
  useMemo,
  useSyncExternalStore,
} from "react";

export const ColorModeContext = createContext({
  rawColorMode: "system",
  resolvedColorMode: "light",
  toggleColorMode: () => {},
  setColorMode: () => {},
});
export const UploadFilesContext = createContext(null);
export const DispatchContext = createContext(null);
export const EventLoopContext = createContext(null);
export const StateStoreContext = createContext(null);

ColorModeContext.displayName = "ColorModeContext";
UploadFilesContext.displayName = "UploadFilesContext";
DispatchContext.displayName = "DispatchContext";
EventLoopContext.displayName = "EventLoopContext";
StateStoreContext.displayName = "StateStoreContext";

/**
 * Subscribe a component to one Python substate in the shared store.
 *
 * With ``fields``, the component re-renders only when one of those fields
 * changes, and the returned object may hold stale values for other fields.
 *
 * @param {string} name - The dotted Python state name.
 * @param {string[]} [fields] - The substate fields the component reads.
 * @returns {object} The current state value for the named substate.
 */
export function useStateContext(name, fields) {
  const store = useContext(StateStoreContext);
  // The compiler passes a new array literal on each render, so key on content.
  const fieldsKey = fields?.join(",");
  const [subscribe, getSnapshot] = useMemo(() => {
    let last;
    return [
      (listener) => store.subscribe(name, listener),
      () => {
        const next = store.getSnapshot(name) ?? app.initialState?.[name];
        if (
          fields !== undefined &&
          last !== undefined &&
          fields.every((field) => Object.is(last[field], next[field]))
        ) {
          return last;
        }
        return (last = next);
      },
    ];
  }, [store, name, fieldsKey]);
  return useSyncExternalStore(subscribe, getSnapshot, getSnapshot);
}

// Values the generated context module registers each time it executes. The
// static runtime reads them through this object at call time instead of
// importing the generated module, so a compile never re-executes the runtime.
export const app = {};

/**
 * Register the app data generated by the compiler.
 *
 * @param {object} values - The generated exports of the context module.
 */
export function registerApp(values) {
  Object.assign(app, values);
}

