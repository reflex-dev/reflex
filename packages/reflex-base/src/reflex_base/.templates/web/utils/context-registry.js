// Components reach addEvents/connectErrors through this object instead of
// hoisting ``useContext(EventLoopContext)`` so JSX literals (e.g.
// ``ErrorBoundary.onError``) constructed in any JS scope can dispatch events.
// Kept here so a re-executed generated module still reaches the mounted
// provider.
export const eventLoop = {
  addEvents: (events, args, event_actions) => {
    console.warn("addEvents called before EventLoopProvider mounted", events);
  },
  connectErrors: [],
};
