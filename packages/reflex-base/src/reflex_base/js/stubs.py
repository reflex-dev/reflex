"""Type stubs for JavaScript modules imported from Python.

A stub sits next to its module (``party.js`` gets ``party.pyi``), so type
checkers resolve ``from my_app.scripts.party import celebrate`` and check the
call. Argument types come from the module's TypeScript annotations or JSDoc,
read by ``script-signatures.js`` in the app's ``.web``; without them, the
arguments are untyped.
"""

from __future__ import annotations

import hashlib
import keyword
import re
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import TypedDict

from reflex_base.js.finder import SCRIPT_EXTENSIONS

# Bumped when the stub format changes, so every stub is rewritten.
_STUB_VERSION = "1"

# Installed with an app that imports a JavaScript module, to read its types.
# Kept equal to the typescript reflex-frontend type-checks itself with.
TYPESCRIPT_PACKAGE = "typescript@5.9.3"

# The script in .web that prints the signatures of modules' exports.
SIGNATURES_SCRIPT = "script-signatures.js"

_HEADER = "# Generated by Reflex from {name} ({digest}); rewritten when it changes."

_IMPORTS = """\
from collections.abc import Mapping, Sequence
from typing import Any, overload

from reflex_base.event import EventCallback, EventSpec
from reflex_base.vars.base import Var
"""

# TypeScript types with a Python counterpart, by their checker spelling.
_SIMPLE_TYPES = {
    "number": "float",
    "bigint": "int",
    "string": "str",
    "boolean": "bool",
    "true": "bool",
    "false": "bool",
    "null": "None",
    "undefined": "None",
    "void": "None",
    "object": "Mapping[str, Any]",
}
_GENERIC_RE = re.compile(
    r"(Array|ReadonlyArray|Set|ReadonlySet|Promise)<(.*)>", re.DOTALL
)
_STRING_LITERAL_RE = re.compile(r"""(["'`]).*\1""", re.DOTALL)
_NUMBER_LITERAL_RE = re.compile(r"-?\d[\d_]*(\.\d+)?")


class Parameter(TypedDict):
    """A parameter of a signature, as ``script-signatures.js`` prints it."""

    name: str
    type: str
    optional: bool
    rest: bool


class Signature(TypedDict):
    """A call signature of an export."""

    parameters: list[Parameter]


class Export(TypedDict):
    """An export and its call signatures; none when it is not a function."""

    name: str
    signatures: list[Signature]


def module_digest(path: Path) -> str:
    """Hash a module and the script files beside it, which its types may use.

    Args:
        path: The module.

    Returns:
        A short hex digest.
    """
    digest = hashlib.sha256(_STUB_VERSION.encode())
    for file in sorted(path.parent.iterdir()):
        if file.suffix in SCRIPT_EXTENSIONS:
            digest.update(file.name.encode())
            digest.update(b"\0")
            digest.update(file.read_bytes())
            digest.update(b"\0")
    return digest.hexdigest()[:16]


def stub_header(path: Path, digest: str) -> str:
    """Get the first line of a module's stub, which records what it was made from.

    Args:
        path: The module.
        digest: Its ``module_digest``.

    Returns:
        The header line.
    """
    return _HEADER.format(name=path.name, digest=digest)


def _split_top_level(text: str, separator: str) -> list[str]:
    """Split a type at the separators outside brackets and string literals.

    Args:
        text: The type.
        separator: A one-character separator.

    Returns:
        The parts, stripped.
    """
    parts: list[str] = []
    depth = 0
    quote = ""
    start = 0
    for index, char in enumerate(text):
        if quote:
            if char == quote:
                quote = ""
        elif char in "\"'`":
            quote = char
        elif char in "([{<":
            depth += 1
        elif char in ")]}>":
            depth -= 1
        elif char == separator and depth == 0:
            parts.append(text[start:index].strip())
            start = index + 1
    parts.append(text[start:].strip())
    return [part for part in parts if part]


def python_type(ts_type: str) -> str:
    """Translate a TypeScript type to the Python type of a value sent as JSON.

    Types with no JSON counterpart, such as functions, DOM elements or a
    library's own types, become ``Any``.

    Args:
        ts_type: The type, as the TypeScript checker prints it.

    Returns:
        The Python type.
    """
    ts_type = ts_type.strip().removeprefix("readonly ")
    union = _split_top_level(ts_type, "|")
    if len(union) > 1:
        members = dict.fromkeys(python_type(member) for member in union)
        return "Any" if "Any" in members else " | ".join(members)
    if ts_type.startswith("(") and ts_type.endswith(")"):
        inner = ts_type[1:-1]
        if _split_top_level(inner, ",") == [inner.strip()] and "=>" not in ts_type:
            return python_type(inner)
    if ts_type.endswith("[]"):
        return f"Sequence[{python_type(ts_type[:-2])}]"
    if match := _GENERIC_RE.fullmatch(ts_type):
        inner = python_type(match.group(2))
        return inner if match.group(1) == "Promise" else f"Sequence[{inner}]"
    if ts_type.startswith("["):
        return "Sequence[Any]"
    if ts_type.startswith(("{", "Record<", "Map<")):
        return "Mapping[str, Any]"
    if _STRING_LITERAL_RE.fullmatch(ts_type):
        return "str"
    if _NUMBER_LITERAL_RE.fullmatch(ts_type):
        return "float"
    return _SIMPLE_TYPES.get(ts_type, "Any")


def _annotation(ts_type: str) -> str:
    """Get the annotation of a parameter: its value, or a Var of it.

    A string parameter also takes an event handler, which is sent as its name.

    Args:
        ts_type: The parameter's TypeScript type.

    Returns:
        The annotation.
    """
    value = python_type(ts_type)
    if value == "Any":
        return "Any"
    handler = (
        " | EventCallback[*tuple[Any, ...]]" if "str" in value.split(" | ") else ""
    )
    return f"{value} | Var[{value}]{handler}"


def _render_signature(name: str, signature: Signature) -> str:
    """Render one signature of an export as a ``def``.

    Arguments are positional-only, since JavaScript passes them by position,
    so a parameter name that is not a Python identifier is renamed safely.

    Args:
        name: The export name.
        signature: The signature.

    Returns:
        The ``def`` line.
    """
    params: list[str] = []
    rest = ""
    optional = False
    for index, parameter in enumerate(signature["parameters"]):
        param_name = parameter["name"]
        if not param_name.isidentifier() or keyword.iskeyword(param_name):
            param_name = f"arg{index}"
        if parameter["rest"]:
            rest = f"*{param_name}: {_annotation(parameter['type'])}"
            break
        optional = optional or parameter["optional"]
        ts_type = parameter["type"]
        if parameter["optional"]:
            # The checker adds `undefined` to an optional parameter's type.
            ts_type = (
                " | ".join(
                    member
                    for member in _split_top_level(ts_type, "|")
                    if member != "undefined"
                )
                or "undefined"
            )
        params.append(
            f"{param_name}: {_annotation(ts_type)}" + (" = ..." if optional else "")
        )
    rendered = [*params, "/"] if params else []
    if rest:
        rendered.append(rest)
    return f"def {name}({', '.join(rendered)}) -> EventSpec: ..."


def _importable(name: str) -> bool:
    """Whether an export can be imported in Python.

    Args:
        name: The export name.

    Returns:
        Whether it is an identifier and not a keyword.
    """
    return name.isidentifier() and not keyword.iskeyword(name)


def render_stub(path: Path, digest: str, exports: Iterable[Export]) -> str:
    """Render the stub of a module from its exports' signatures.

    Exports that are not functions, and those Python cannot import, are left
    out. An export with several signatures gets one overload each.

    Args:
        path: The module.
        digest: Its ``module_digest``.
        exports: Its exports.

    Returns:
        The ``.pyi`` source.
    """
    lines = [stub_header(path, digest), _IMPORTS]
    for export in exports:
        signatures = export["signatures"]
        if not signatures or not _importable(export["name"]):
            continue
        for signature in signatures:
            if len(signatures) > 1:
                lines.append("@overload")
            lines.append(_render_signature(export["name"], signature))
    return "\n".join(lines) + "\n"


def render_untyped_stub(path: Path, digest: str, names: Sequence[str]) -> str:
    """Render the stub of a module whose types could not be read.

    Args:
        path: The module.
        digest: Its ``module_digest``.
        names: Its export names.

    Returns:
        The ``.pyi`` source, with untyped arguments.
    """
    lines = [stub_header(path, digest), _IMPORTS]
    lines.extend(
        f"def {name}(*args: Any) -> EventSpec: ..."
        for name in names
        if _importable(name)
    )
    return "\n".join(lines) + "\n"


def exports_by_file(output: Mapping[str, list[Export]]) -> dict[Path, list[Export]]:
    """Key the output of ``script-signatures.js`` by resolved path.

    Args:
        output: The parsed JSON.

    Returns:
        The exports of each module.
    """
    return {Path(file).resolve(): exports for file, exports in output.items()}
