"""Type stubs for JavaScript modules imported from Python.

A stub sits next to its module (``party.js`` gets ``party.pyi``), so type
checkers resolve ``from my_app.scripts.party import celebrate`` and check the
call. A stub declares the functions the compiler found the module exports.
``script-signatures.js``, run in the app's ``.web``, reads their parameters
from TypeScript annotations or JSDoc and classifies their types into the JSON
values Python can send; this module renders them.

Internal: what an app relies on is the stub itself, which
``docs/api-reference/browser_javascript.md`` documents.
"""

from __future__ import annotations

import functools
import hashlib
import json
import keyword
import os
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Literal, TypeAlias, TypedDict

from reflex_base import constants

# Installed with an app that imports a JavaScript module, to read its types.
# Kept equal to the typescript reflex-frontend type-checks itself with.
_TYPESCRIPT_PACKAGE = "typescript@5.9.3"

# The script in .web that prints the signatures of modules' exports.
_SIGNATURES_SCRIPT = "script-signatures.js"

_HEADER_PREFIX = "# Generated by Reflex from "
_HEADER = _HEADER_PREFIX + "{name} ({digest}); rewritten when it changes."

# The modules of the names a stub uses for types, in import order. The stub
# imports them as private aliases (`_str`), so that an export named `str` or
# `Var` cannot replace one.
_TYPE_MODULES = {
    "builtins": ("bool", "float", "str", "tuple"),
    "collections.abc": ("Mapping", "Sequence"),
    "typing": ("Any", "Literal", "overload"),
    "reflex_base.event": ("EventCallback", "EventSpec"),
    "reflex_base.vars.base": ("Var",),
}
_ALIASES = frozenset(f"_{name}" for names in _TYPE_MODULES.values() for name in names)

# The JSON types `script-signatures.js` classifies parameters into, whose
# grammar it documents.
_Leaf: TypeAlias = Literal["any", "str", "float", "bool", "None"]
_LEAF_NAMES = {"any": "Any", "str": "str", "float": "float", "bool": "bool"}


class _JsonLiteral(TypedDict):
    """A literal string, integer or boolean."""

    kind: Literal["literal"]
    value: str | int | bool


class _JsonList(TypedDict):
    """An array or tuple, of the union of its items' types."""

    kind: Literal["list"]
    item: JsonType


class _JsonMapping(TypedDict):
    """An object with string keys."""

    kind: Literal["mapping"]
    value: JsonType


class _JsonUnion(TypedDict):
    """A union of two or more types."""

    kind: Literal["union"]
    members: list[JsonType]


JsonType: TypeAlias = "_Leaf | _JsonLiteral | _JsonList | _JsonMapping | _JsonUnion"


class Parameter(TypedDict):
    """A parameter of a signature, as ``script-signatures.js`` prints it."""

    name: str
    type: JsonType
    optional: bool
    rest: bool


class Signature(TypedDict):
    """A call signature of an export."""

    parameters: list[Parameter]


class Signatures(TypedDict):
    """What ``script-signatures.js`` prints."""

    # The version of this shape, which the script changes with it.
    format: Literal[1]
    # The call signatures of each module's exports, by module, then by name.
    modules: dict[str, dict[str, list[Signature]]]
    # The files each module's types are read from, by module: it and the local
    # files it reaches.
    files: dict[str, list[str]]


@functools.cache
def _renderer_digest() -> bytes:
    """Hash the code that makes a stub, so a change to it rewrites every stub.

    Returns:
        The digest of this module and ``script-signatures.js``.
    """
    script = constants.Templates.Dirs.WEB_TEMPLATE / _SIGNATURES_SCRIPT
    return hashlib.sha256(Path(__file__).read_bytes() + script.read_bytes()).digest()


def _module_digest(path: Path, files: Iterable[str], dependencies: bytes) -> str:
    """Hash what a module's stub is made from.

    That is the files the module reaches and those its types were read from,
    what decides the installed packages, whose declarations it may use, and
    the code that makes stubs.

    Args:
        path: The module.
        files: Those files; a file that no longer exists changes the digest.
        dependencies: The app's ``package.json`` and lockfile.

    Returns:
        A short hex digest.
    """
    digest = hashlib.sha256(_renderer_digest())
    # Relative, so the same sources give the same stub on every machine.
    for name in sorted({os.path.relpath(file, path.parent) for file in files}):
        try:
            content = (path.parent / name).read_bytes()
        except FileNotFoundError:
            digest.update(name.encode() + b"\1")
            continue
        digest.update(name.encode() + b"\0")
        digest.update(content)
        digest.update(b"\0")
    digest.update(dependencies)
    return digest.hexdigest()[:16]


def _stub_header(path: Path, digest: str) -> str:
    """Get the first line of a module's stub, which records what it was made from.

    Args:
        path: The module.
        digest: Its ``_module_digest``.

    Returns:
        The header line.
    """
    return _HEADER.format(name=path.name, digest=digest)


def _read_header(stub: Path) -> str | None:
    """Read the first line of a stub.

    Args:
        stub: The stub.

    Returns:
        The line, or None if there is no such file.
    """
    try:
        with stub.open(encoding="utf-8") as file:
            return file.readline().rstrip("\n")
    except FileNotFoundError:
        return None


def _is_generated(header: str | None) -> bool:
    """Whether a stub's header says Reflex wrote it, and so may rewrite it.

    Args:
        header: The stub's first line, from ``_read_header``.

    Returns:
        Whether it is a header ``_stub_header`` makes.
    """
    return header is not None and header.startswith(_HEADER_PREFIX)


def _use(name: str, used: set[str]) -> str:
    """Get a stub's alias for a type name, and record that the stub imports it.

    Args:
        name: The name, such as ``str``.
        used: The names the stub uses.

    Returns:
        The alias, such as ``_str``.
    """
    used.add(name)
    return f"_{name}"


def _render_literal(value: str | int | bool) -> str:
    """Render a literal value as Python source.

    Args:
        value: The value.

    Returns:
        The source: a double-quoted string, ``True``, ``False`` or a number.
    """
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return repr(value)


def _render_union(
    members: list[JsonType], used: set[str], items_take_vars: bool = False
) -> str:
    """Render the Python type of a union of JSON values.

    Its literals are merged into one ``Literal``, after the other members and
    before ``None``.

    Args:
        members: The union's members.
        used: The names the stub uses, which this adds to.
        items_take_vars: Whether the items of its containers may be Vars.

    Returns:
        The type.
    """
    rendered: list[str] = []
    literals: list[str] = []
    for member in members:
        if isinstance(member, dict) and member["kind"] == "literal":
            literals.append(_render_literal(member["value"]))
        elif member != "None":
            rendered.append(_render_type(member, used, items_take_vars))
    if literals:
        rendered.append(f"{_use('Literal', used)}[{', '.join(literals)}]")
    if "None" in members:
        rendered.append("None")
    return " | ".join(rendered)


def _render_type(type_: JsonType, used: set[str], items_take_vars: bool = False) -> str:
    """Render the Python type of a JSON value.

    Args:
        type_: The JSON type.
        used: The names the stub uses, which this adds to.
        items_take_vars: Whether each item of a list and value of a mapping
            may also be a Var, which the event sends as the value it holds.

    Returns:
        The type.
    """
    if isinstance(type_, str):
        return "None" if type_ == "None" else _use(_LEAF_NAMES[type_], used)
    if type_["kind"] == "literal":
        return f"{_use('Literal', used)}[{_render_literal(type_['value'])}]"
    if type_["kind"] == "list":
        item = _render_item(type_["item"], used, items_take_vars)
        return f"{_use('Sequence', used)}[{item}]"
    if type_["kind"] == "mapping":
        value = _render_item(type_["value"], used, items_take_vars)
        return f"{_use('Mapping', used)}[{_use('str', used)}, {value}]"
    return _render_union(type_["members"], used, items_take_vars)


def _render_item(type_: JsonType, used: set[str], takes_var: bool) -> str:
    """Render the type of an item of a list or a value of a mapping.

    Args:
        type_: The item's JSON type.
        used: The names the stub uses, which this adds to.
        takes_var: Whether the item may also be a Var.

    Returns:
        The type.
    """
    item = _render_type(type_, used, takes_var)
    if not takes_var or type_ == "any":
        return item
    return f"{item} | {_use('Var', used)}[{_render_type(type_, used)}]"


def _annotation(type_: JsonType, used: set[str]) -> str:
    """Get the annotation of a parameter: its value, or a Var of it.

    A string parameter also takes an event handler, which is sent as its name.

    Args:
        type_: The parameter's JSON type.
        used: The names the stub uses, which this adds to.

    Returns:
        The annotation.
    """
    if type_ == "any":
        return _use("Any", used)
    value = _render_type(type_, used, items_take_vars=True)
    annotation = f"{value} | {_use('Var', used)}[{_render_type(type_, used)}]"
    if type_ == "str" or (
        not isinstance(type_, str)
        and type_["kind"] == "union"
        and "str" in type_["members"]
    ):
        handler = _use("EventCallback", used)
        annotation += f" | {handler}[*{_use('tuple', used)}[{_use('Any', used)}, ...]]"
    return annotation


def _render_signature(name: str, signature: Signature, used: set[str]) -> str:
    """Render one signature of an export as a ``def``.

    Arguments are positional-only, since JavaScript passes them by position,
    so a parameter name that is not a Python identifier is renamed safely.

    Args:
        name: The export name.
        signature: The signature.
        used: The names the stub uses, which this adds to.

    Returns:
        The ``def`` line.
    """
    parameters = signature["parameters"]
    rest_index = next(
        (index for index, parameter in enumerate(parameters) if parameter["rest"]),
        len(parameters),
    )
    # Python can only omit trailing arguments: a parameter with a default that a
    # required one follows is required.
    omittable = rest_index
    while omittable > 0 and parameters[omittable - 1]["optional"]:
        omittable -= 1
    # Rename the parameters that are not Python identifiers to names no other
    # parameter has; arguments are positional-only, so callers never see them.
    names = {
        parameter["name"]
        for parameter in parameters
        if parameter["name"].isidentifier() and not keyword.iskeyword(parameter["name"])
    }
    params: list[str] = []
    rest = ""
    for index, parameter in enumerate(parameters[: rest_index + 1]):
        param_name = parameter["name"]
        if param_name not in names:
            param_name = f"arg{index}"
            while param_name in names:
                param_name += "_"
            names.add(param_name)
        annotation = _annotation(parameter["type"], used)
        if parameter["rest"]:
            rest = f"*{param_name}: {annotation}"
            break
        default = " = ..." if index >= omittable else ""
        params.append(f"{param_name}: {annotation}{default}")
    rendered = [*params, "/"] if params else []
    if rest:
        rendered.append(rest)
    return f"def {name}({', '.join(rendered)}) -> {_use('EventSpec', used)}: ..."


def _importable(name: str) -> bool:
    """Whether an export can be imported in Python.

    Args:
        name: The export name.

    Returns:
        Whether it is an identifier, not a keyword, not a special name, which
        the module does not provide, and not one of the stub's own names for
        the types it uses.
    """
    return (
        name.isidentifier()
        and not keyword.iskeyword(name)
        and not name.startswith("__")
        and name not in _ALIASES
    )


def _render_imports(used: set[str]) -> list[str]:
    """Render the imports of the names a stub uses, the standard library first.

    Args:
        used: The names.

    Returns:
        The import lines.
    """
    groups: tuple[list[str], list[str]] = ([], [])
    for module, names in _TYPE_MODULES.items():
        if aliases := [f"{name} as _{name}" for name in names if name in used]:
            group = groups[module.startswith("reflex_base.")]
            group.append(f"from {module} import {', '.join(aliases)}")
    return [*groups[0], *([""] if all(groups) else []), *groups[1]]


def _render_stub(
    path: Path,
    digest: str,
    functions: Iterable[str],
    signatures: Mapping[str, list[Signature]],
) -> str:
    """Render the stub of a module.

    It declares the functions the module exports that Python can import. One
    TypeScript has no signature for, such as one of unknown type or of a module
    whose types could not be read, takes any arguments; one with several gets
    an overload each.

    Args:
        path: The module.
        digest: Its ``_module_digest``.
        functions: The names it exports as functions, as the compiler found.
        signatures: The signatures of its exports by name, from
            ``script-signatures.js``.

    Returns:
        The ``.pyi`` source.
    """
    used: set[str] = set()
    definitions: list[str] = []
    for name in filter(_importable, functions):
        overloads = signatures.get(name, [])
        if not overloads:
            any_ = _use("Any", used)
            definitions.append(
                f"def {name}(*args: {any_}) -> {_use('EventSpec', used)}: ..."
            )
        for signature in overloads:
            if len(overloads) > 1:
                definitions.append(f"@{_use('overload', used)}")
            definitions.append(_render_signature(name, signature, used))
    lines = [_stub_header(path, digest)]
    if definitions:
        lines.extend([*_render_imports(used), "", *definitions])
    return "\n".join(lines) + "\n"
