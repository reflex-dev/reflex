"""Compile ``.po`` catalogs into the per-locale JS modules served to clients."""

from __future__ import annotations

import gettext
import json
import logging
import re
from collections.abc import Sequence
from pathlib import Path
from typing import TYPE_CHECKING

from .config import LOCALE_COOKIE_NAME, I18nConfig, get_active_catalog_dirs
from .registry import MessageKey, format_message_list

if TYPE_CHECKING:
    from babel.messages.catalog import Catalog, Message

logger = logging.getLogger(__name__)

_FALLBACK_PLURAL_EXPR = "n != 1"

# What gettext accepts but JS reads differently: "/" divides integers only in
# gettext, and a leading zero ("010") is a syntax error in a JS module.
_JS_DIVERGENT_PLURAL_RE = re.compile(r"/|\b0\d")

_GENERATED_HEADER = "// Generated by Reflex. Do not edit.\n"


def _is_portable_plural_expr(expr: str) -> bool:
    """Whether gettext and the client's JS evaluate a plural rule alike.

    Args:
        expr: The C plural expression from a catalog header.

    Returns:
        True if gettext parses the rule and JS reads it the same way.
    """
    try:
        # gettext admits only n, integers, parentheses and C operators, so a
        # rule it parses cannot inject code into the client's JS.
        gettext.c2py(expr)
    except ValueError:
        return False
    return _JS_DIVERGENT_PLURAL_RE.search(expr) is None


def read_po_catalog(path: Path, locale: str | None = None) -> Catalog:
    """Parse a ``.po`` catalog file.

    A plural rule gettext cannot parse, or JS would evaluate differently, is
    replaced by the generic one, so the server and the client pick forms by
    the same rule.

    Args:
        path: The path of the ``.po`` file.
        locale: The catalog's locale, supplying CLDR plural rules for a file
            whose header declares none.

    Returns:
        The parsed catalog.
    """
    from babel.messages.pofile import read_po

    with path.open("r", encoding="utf-8") as po_file:
        try:
            catalog = read_po(po_file, locale=locale and locale.replace("-", "_"))
        except ValueError:
            # A tag Babel has no CLDR data for; the catalog's own header (or
            # the generic rule) decides the plural forms. read_po builds the
            # Catalog before reading, so nothing was consumed.
            catalog = read_po(po_file)
    expr = catalog.plural_expr
    if not _is_portable_plural_expr(expr):
        logger.warning(
            f"Ignoring unsupported Plural-Forms expression {expr!r} in {path}; "
            f"falling back to {_FALLBACK_PLURAL_EXPR!r}."
        )
        catalog.mime_headers = [
            ("Plural-Forms", f"nplurals=2; plural={_FALLBACK_PLURAL_EXPR};")
        ]
    return catalog


def is_translated(message: Message) -> bool:
    """Whether a catalog entry carries a usable translation.

    Args:
        message: The catalog entry.

    Returns:
        False for a fuzzy (stale) entry or one with an empty (plural) form.
    """
    if message.fuzzy:
        return False
    strings = message.string
    if isinstance(strings, str):
        return bool(strings)
    return bool(strings) and all(strings)


def load_catalog(locale: str) -> Catalog | None:
    """Read a locale's catalogs: the app's, completed by its catalog packages'.

    The app's translation of a message wins; a package's fills in where the app
    has none (or only a fuzzy or partial one).

    Args:
        locale: The locale whose catalogs to read.

    Returns:
        The merged catalog, or None if no catalog directory has the locale.
    """
    merged: Catalog | None = None
    for catalog_dir in get_active_catalog_dirs():
        path = catalog_dir / f"{locale}.po"
        if not path.exists():
            continue
        catalog = read_po_catalog(path, locale)
        if merged is None:
            merged = catalog
            continue
        for message in catalog:
            if not message.id or not is_translated(message):
                continue
            current = merged.get(message.id, message.context)
            if current is not None:
                if is_translated(current):
                    continue
                # Assigning onto an existing entry would keep its empty string.
                merged.delete(message.id, message.context)
            merged[message.id] = message
    return merged


def compile_catalog_module(
    catalog: Catalog | None,
    used_messages: Sequence[MessageKey],
    locale: str,
    *,
    is_default_locale: bool,
) -> str:
    """Render the JS catalog module for one locale (used messages only).

    Args:
        catalog: The catalog from :func:`read_po_catalog`, whose plural rule
            is embedded as is, or None if the locale has none.
        used_messages: All messages collected from ``rx.t`` calls.
        locale: The locale being compiled, for warnings.
        is_default_locale: If True, missing translations are not warned about.

    Returns:
        The JS module source code.
    """
    entries: list[str] = []
    missing: list[MessageKey] = []
    for key in used_messages:
        translation = _lookup_translation(catalog, key)
        if translation is None:
            missing.append(key)
            continue
        entries.append(f"  [{json.dumps(key.catalog_key)}, {json.dumps(translation)}],")
    if missing and not is_default_locale:
        logger.warning(
            f"{len(missing)} translation(s) missing for locale {locale!r} "
            f"(falling back to the default locale):\n{format_message_list(missing)}"
        )
    messages_body = "\n".join(entries)
    plural = catalog.plural_expr if catalog is not None else _FALLBACK_PLURAL_EXPR
    # A Map, not an object literal: a message named like a prototype member
    # ("constructor", "__proto__") must miss rather than resolve to one.
    return (
        f"{_GENERATED_HEADER}"
        f"export const plural = (n) => Number({plural});\n"
        f"export const messages = new Map([\n{messages_body}\n]);\n"
    )


def _lookup_translation(
    catalog: Catalog | None, key: MessageKey
) -> str | list[str] | None:
    """Find the translation for a message in a catalog.

    Args:
        catalog: The parsed catalog, or None.
        key: The message to look up.

    Returns:
        The translated string, a list of plural forms, or None if the message
        is untranslated (including partially translated plurals).
    """
    if catalog is None:
        return None
    message = catalog.get(key.msgid, key.context)
    # A fuzzy entry carries a stale translation; fall back to the source text
    # (the server side already excludes fuzzy via write_mo).
    if message is None or not is_translated(message):
        return None
    strings = message.string
    if key.plural is None:
        return strings if isinstance(strings, str) else None
    if isinstance(strings, str):
        return [strings]
    return list(strings) if strings else None


def default_plural_expr_js(catalog: Catalog | None, locale: str) -> str:
    """The default locale's plural expression for the client-side fallback.

    Args:
        catalog: The default locale's catalog from :func:`read_po_catalog`,
            if one exists.
        locale: The default locale.

    Returns:
        A validated JS plural expression over the variable ``n``.
    """
    if catalog is None:
        from babel.messages.catalog import Catalog as BabelCatalog

        try:
            # Babel's built-in CLDR plural table for the locale.
            catalog = BabelCatalog(locale=locale.replace("-", "_"))
        except ValueError:
            return _FALLBACK_PLURAL_EXPR
    return catalog.plural_expr


def compile_index_module(
    config: I18nConfig,
    *,
    url_routing: bool = False,
    default_at_root: bool = True,
    deploy_url: str = "",
    default_plural_expr: str = _FALLBACK_PLURAL_EXPR,
) -> str:
    """Render the JS module describing the app's locales and catalog loaders.

    The static ``import()`` map lets the bundler code-split one chunk per
    locale, so clients only ever download the active language.

    Args:
        config: The app's i18n configuration.
        url_routing: Whether URL-based locale routing is enabled (so the client
            knows the locale comes from the URL, not the cookie).
        default_at_root: Whether URL routing serves the default locale at the
            unprefixed path (used by the hreflang helper).
        deploy_url: Absolute site URL for building absolute hreflang hrefs, or
            empty to emit relative hrefs.
        default_plural_expr: The default locale's plural expression, used
            client-side to pick between the two source strings of a plural
            message that has no catalog entry.

    Returns:
        The JS module source code.
    """
    loaders = "\n".join(
        f"  {json.dumps(locale)}: () => import({json.dumps(f'$/i18n/{locale}.js')}),"
        for locale in config.locales
    )
    return (
        f"{_GENERATED_HEADER}"
        f"export const locales = {json.dumps(list(config.locales))};\n"
        f"export const defaultLocale = {json.dumps(config.default_locale)};\n"
        f"export const fallbackLocale = {json.dumps(config.fallback_locale)};\n"
        f"export const cookieName = {json.dumps(LOCALE_COOKIE_NAME)};\n"
        f"export const urlRouting = {json.dumps(url_routing)};\n"
        f"export const defaultAtRoot = {json.dumps(default_at_root)};\n"
        f"export const deployUrl = {json.dumps(deploy_url)};\n"
        f"export const defaultPlural = (n) => Number({default_plural_expr});\n"
        f"export const loaders = {{\n{loaders}\n}};\n"
    )
