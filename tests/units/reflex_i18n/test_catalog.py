def test_compile_catalog_polish_plural_expr():
    catalog = Catalog(locale="pl")
    module = compile_catalog_module(catalog, [], "pl", is_default_locale=False)
    # Polish has a 3-form plural; the C expression is whitelisted and kept.
    assert module == (
        "// Generated by Reflex. Do not edit.\n"
        "export const plural = (n) => Number((n==1 ? 0 : n%10>=2 && n%10<=4 && "
        "(n%100<10 || n%100>=20) ? 1 : 2));\n"
        "export const messages = new Map([\n\n]);\n"
    )


def test_compile_catalog_skips_fuzzy_entries():
    # A fuzzy entry carries a stale translation; the client must fall back to
    # the source msgid (matching the server, where write_mo excludes fuzzy).
    catalog = Catalog(locale="de")
    catalog.add("Hello", "Hallo (veraltet)", flags=("fuzzy",))
    module = compile_catalog_module(
        catalog, [MessageKey("Hello")], "de", is_default_locale=False
    )
    assert module == (
        "// Generated by Reflex. Do not edit.\n"
        "export const plural = (n) => Number((n != 1));\n"
        "export const messages = new Map([\n\n]);\n"
    )


def test_compile_catalog_warns_only_about_messages_missing_by_accident(
    caplog: pytest.LogCaptureFixture,
):
    """A read-only entry is untranslated on purpose and shows the source text."""
    catalog = Catalog(locale="de")
    catalog.add("Imprint", flags=("read-only",))
    catalog.add("Privacy")
    module = compile_catalog_module(
        catalog,
        [MessageKey("Imprint"), MessageKey("Privacy")],
        "de",
        is_default_locale=False,
    )
    assert module == (
        "// Generated by Reflex. Do not edit.\n"
        "export const plural = (n) => Number((n != 1));\n"
        "export const messages = new Map([\n\n]);\n"
    )
    assert _warnings(caplog) == [
        (
            "1 translation(s) missing for locale 'de' (falling back to the "
            "default locale):\n  'Privacy'"
        )
    ]


@pytest.mark.parametrize(
    ("string", "flags", "expected"),
    [
        ("", ("read-only",), True),
        (("", ""), ("read-only",), True),
        ("Impressum", ("read-only",), False),
        (("Artikel", ""), ("read-only",), False),
        ("", ("read-only", "fuzzy"), False),
        ("", (), False),
    ],
)
def test_is_left_untranslated(
    string: str | tuple[str, str], flags: tuple[str, ...], expected: bool
):
    message_id = ("Item", "Items") if isinstance(string, tuple) else "Imprint"
    catalog = Catalog(locale="de")
    message = catalog.add(message_id, string, flags=flags)
    assert is_left_untranslated(message) is expected


