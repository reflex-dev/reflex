def test_default_plural_expr_from_babel_table():
    # No default catalog: the expression comes from Babel's CLDR table.
    assert default_plural_expr_js(None, "fr") == "(n > 1)"
    assert default_plural_expr_js(None, "en") == "(n != 1)"


def _write_po(tmp_path: Path, locale: str, header_lines: str = "") -> Path:
    """Write a .po file holding only a header.

    Args:
        tmp_path: The directory to write it to.
        locale: The file's locale.
        header_lines: Header lines after the Content-Type.

    Returns:
        The written file.
    """
    po_path = tmp_path / f"{locale}.po"
    po_path.write_text(
        'msgid ""\nmsgstr ""\n'
        '"Content-Type: text/plain; charset=UTF-8\\n"\n'
        f"{header_lines}\n",
        encoding="utf-8",
    )
    return po_path


def test_default_plural_expr_prefers_catalog_header(tmp_path: Path):
    # An expression the CLDR table would never produce for "fr", so the test
    # fails if the catalog's own Plural-Forms header stops being preferred.
    catalog = read_po_catalog(
        _write_po(tmp_path, "fr", '"Plural-Forms: nplurals=2; plural=(n > 2);\\n"'),
        "fr",
    )
    assert default_plural_expr_js(catalog, "fr") == "(n > 2)"


def test_read_po_catalog_uses_locale_plural_rules(tmp_path: Path):
    # No Plural-Forms header: the locale supplies Babel's CLDR rule rather than
    # the generic English one.
    catalog = read_po_catalog(_write_po(tmp_path, "fr"), "fr")
    assert catalog.plural_expr == "(n > 1)"
    assert read_po_catalog(_write_po(tmp_path, "pt-BR"), "pt-BR").locale is not None


@pytest.mark.parametrize("expr", ["alert('xss')", "(n !== 1)", "n/10 == 1", "n == 010"])
def test_read_po_catalog_replaces_an_unsupported_plural_rule(
    tmp_path: Path, caplog: pytest.LogCaptureFixture, expr: str
):
    # The rule is embedded in the client's JS and run by gettext on the server;
    # one gettext cannot parse (code, or JS-only syntax), or that JS evaluates
    # differently (float division, a leading-zero literal), gives way to the
    # generic rule for both.
    header = f'"Plural-Forms: nplurals=2; plural={expr};\\n"'
    po_path = _write_po(tmp_path, "de", header)
    catalog = read_po_catalog(po_path, "de")
    assert _warnings(caplog) == [
        (
            f"Ignoring unsupported Plural-Forms expression {expr!r} in {po_path}; "
            "falling back to 'n != 1'."
        )
    ]
    assert catalog.plural_expr == "n != 1"
    module = compile_catalog_module(catalog, [], "de", is_default_locale=False)
    assert module == (
        "// Generated by Reflex. Do not edit.\n"
        "export const plural = (n) => Number(n != 1);\n"
        "export const messages = new Map([\n\n]);\n"
    )


def test_read_po_catalog_tolerates_unknown_locale(tmp_path: Path):
    # A well-formed tag Babel has no CLDR data for must not break compilation.
    assert read_po_catalog(_write_po(tmp_path, "qq-ZZ"), "qq-ZZ") is not None


def test_default_plural_expr_invalid_locale_falls_back():
    assert default_plural_expr_js(None, "not a locale") == "n != 1"


_PO_HEADER = (
    'msgid ""\nmsgstr ""\n'
    '"Content-Type: text/plain; charset=UTF-8\\n"\n'
    '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"\n\n'
)


def _write_catalog(catalog_dir: Path, locale: str, body: str) -> None:
    """Write a .po file with the shared header.

    Args:
        catalog_dir: The catalog directory, created if missing.
        locale: The file's locale.
        body: The messages after the header.
    """
    catalog_dir.mkdir(parents=True, exist_ok=True)
    (catalog_dir / f"{locale}.po").write_text(_PO_HEADER + body, encoding="utf-8")


@pytest.fixture
def app_with_catalog_package(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    """Activate an app whose de catalog a package's catalog completes.

    Yields:
        None
    """
    monkeypatch.chdir(tmp_path)
    package_dir = tmp_path / "site" / "mylib"
    package_dir.mkdir(parents=True)
    (package_dir / "__init__.py").write_text("", encoding="utf-8")
    monkeypatch.syspath_prepend(str(tmp_path / "site"))
    _write_catalog(
        tmp_path / "locales",
        "de",
        'msgid "Save"\nmsgstr "Sichern"\n\n'
        'msgid "Cancel"\nmsgstr ""\n\n'
        '#, fuzzy\nmsgid "Delete"\nmsgstr "Entfernen"\n\n'
        '#, read-only\nmsgid "Imprint"\nmsgstr ""\n',
    )
    _write_catalog(
        package_dir / "locales",
        "de",
        'msgid "Save"\nmsgstr "Speichern"\n\n'
        'msgid "Cancel"\nmsgstr "Abbrechen"\n\n'
        'msgid "Delete"\nmsgstr "L\u00f6schen"\n\n'
        'msgid "Back"\nmsgstr ""\n\n'
        'msgid "Imprint"\nmsgstr "Impressum"\n\n'
        'msgctxt "menu"\nmsgid "Open"\nmsgstr "\u00d6ffnen"\n',
    )
    _write_catalog(
        package_dir / "locales", "fr", 'msgid "Save"\nmsgstr "Enregistrer"\n'
    )
    set_active_i18n_config(
        I18nConfig(locales=["en", "de", "fr"], catalog_packages=["mylib"])
    )
    yield
    set_active_i18n_config(None)


@pytest.mark.usefixtures("app_with_catalog_package")
def test_load_catalog_completes_the_app_catalog_with_package_catalogs():
    catalog = load_catalog("de")
    assert catalog is not None
    # The app's translation wins; a package fills in where the app has none,
    # an empty or a fuzzy one, but not where it leaves one out on purpose.
    assert {
        (message.id, message.context): message.string
        for message in catalog
        if message.id and is_translated(message)
    } == {
        ("Save", None): "Sichern",
        ("Cancel", None): "Abbrechen",
        ("Delete", None): "L\u00f6schen",
        ("Open", "menu"): "\u00d6ffnen",
    }
    imprint = catalog.get("Imprint")
    assert imprint is not None
    assert is_left_untranslated(imprint)


