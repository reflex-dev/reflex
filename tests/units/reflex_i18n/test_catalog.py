def _warnings(caplog: pytest.LogCaptureFixture) -> list[str]:
    """The warnings logged so far.

    Args:
        caplog: The log capture.

    Returns:
        Their messages.
    """
    return [r.getMessage() for r in caplog.records if r.levelno == logging.WARNING]


def _catalog(locale: str = "de") -> Catalog:
    """A catalog with a plain, a context and a plural message.

    Args:
        locale: The catalog's locale.

    Returns:
        The catalog.
    """
    catalog = Catalog(locale=locale)
    catalog.add("Hello {name}!", "Hallo {name}!")
    catalog.add("Open", "Öffnen", context="menu")
    catalog.add(
        ("{count} item", "{count} items"),
        ("{count} Artikel", "{count} Artikel"),
    )
    return catalog


def test_compile_index_module():
    config = I18nConfig(locales=["en", "de"], default_locale="en")
    assert compile_index_module(config) == (
        "// Generated by Reflex. Do not edit.\n"
        'export const locales = ["en", "de"];\n'
        'export const defaultLocale = "en";\n'
        'export const fallbackLocale = "en";\n'
        'export const cookieName = "reflex_locale";\n'
        "export const urlRouting = false;\n"
        "export const defaultAtRoot = true;\n"
        'export const deployUrl = "";\n'
        "export const defaultPlural = (n) => Number(n != 1);\n"
        "export const localizedPaths = {};\n"
        "export const loaders = {\n"
        '  "en": () => import("$/i18n/en.js"),\n'
        '  "de": () => import("$/i18n/de.js"),\n'
        "};\n"
    )


def test_compile_catalog_includes_used_messages():
    used = [MessageKey("Hello {name}!"), MessageKey("Open", context="menu")]
    module = compile_catalog_module(_catalog(), used, "de", is_default_locale=False)
    assert module == (
        "// Generated by Reflex. Do not edit.\n"
        "export const plural = (n) => Number((n != 1));\n"
        "export const messages = new Map([\n"
        '  ["Hello {name}!", "Hallo {name}!"],\n'
        '  ["menu\\u0004Open", "\\u00d6ffnen"],\n'
        "]);\n"
    )


