def test_render_stub_maps_types_without_json_form_to_any():
    """Enums are their values; containers keep item types, each also a Var; Set, Map, bigint and the like are Any.

    The stub declares only the functions the compiler lists: a function
    re-exported by name is one, the names of an ``export *`` are not.
    """

    def var(value: str) -> str:
        """Render a type that may also be a Var of it.

        Args:
            value: The type.

        Returns:
            The union of the type and its Var.
        """
        return f"{value} | _Var[{value}]"

    def container(shape: str, item: str, handler: bool = False) -> str:
        """Render a container type whose items, and itself, may be Vars.

        Args:
            shape: The container, with `{}` for its item type.
            item: The item type.
            handler: Whether an item may also be an event handler, as a string
                item may: it is sent as its name.

        Returns:
            The container type.
        """
        # An item may be a Var too, as may the whole container.
        value = var(item) + (f" | {HANDLER}" if handler else "")
        return f"{shape.format(value)} | _Var[{shape.format(item)}]"

    color = var('_Literal["green", "red"]')
    mode = var('_Literal["a", "b", 2, True]')
    shape = var('_Literal["circle", "square"]')

    assert _fixture_stub("types.ts") == (
        "# Generated by Reflex from types.ts; do not edit.\n"
        "from builtins import float as _float, str as _str, tuple as _tuple\n"
        "from collections.abc import Mapping as _Mapping, Sequence as _Sequence\n"
        "from typing import Any as _Any, Literal as _Literal\n"
        "\n"
        "from reflex_base.event import EventCallback as _EventCallback, EventSpec as _EventSpec\n"
        "from reflex_base.vars.base import Var as _Var\n"
        "\n"
        "def aliased() -> _EventSpec: ...\n"
        "def literals("
        f"color: {color}, "
        f"level: {var('_Literal[0, 1]')}, "
        f"mode: {mode}, "
        f"ratio: {FLOAT}, "
        f"flag: {var('_Literal[True]')}, "
        f"shape: {shape}, /) -> _EventSpec: ...\n"
        "def containers("
        f"names: {container('_Sequence[{}]', '_str', handler=True)}, "
        f"pair: {container('_Sequence[{}]', '_float | _str', handler=True)}, "
        f"empty: {var('_Sequence[_Any]')}, "
        f"counts: {container('_Mapping[_str, {}]', '_float')}, "
        f"options: {var('_Mapping[_str, _Any]')}, "
        f"inline: {var('_Mapping[_str, _Any]')}, "
        f"partial: {var('_Mapping[_str, _Any]')}, "
        f"keyed: {var('_Mapping[_str, _Any]')}, "
        f"nested: {container('_Sequence[{}]', '_str | None', handler=True)}, /) -> _EventSpec: ...\n"
        "def noJsonForm(tags: _Any, lookup: _Any, big: _Any, later: _Any, "
        "make: _Any, element: _Any, widget: _Any, anything: _Any, both: _Any, "
        "either: _Any, /) "
        "-> _EventSpec: ...\n"
        f"def maybe(value: _str | None | _Var[_str | None] | {HANDLER} = ..., /, "
        "*rest: _Any) -> _EventSpec: ...\n"
    )


@pytest.mark.parametrize(
    ("json_type", "rendered", "used"),
    [
        ("None", "None", set()),
        (
            {"kind": "literal", "value": 'say "hi" 🎉'},
            '_Literal["say \\"hi\\" 🎉"]',
            {"Literal"},
        ),
        (
            {
                "kind": "union",
                "members": [
                    "None",
                    "str",
                    {"kind": "list", "item": "bool"},
                    {"kind": "literal", "value": -1},
                    {"kind": "literal", "value": False},
                ],
            },
            "_str | _Sequence[_bool] | _Literal[-1, False] | None",
            {"str", "Sequence", "bool", "Literal"},
        ),
    ],
)
def test_render_type(json_type: JsonType, rendered: str, used: set[str]):
    """A union's literals merge into one Literal before None; string literals are escaped.

    Args:
        json_type: The JSON type.
        rendered: Its Python type.
        used: The names it makes the stub import.
    """
    names: set[str] = set()
    assert (_render_type(json_type, names), names) == (rendered, used)


def _param(name: str, type_: JsonType, optional: bool = False) -> Parameter:
    """Build a parameter as script-signatures.js prints it.

    Args:
        name: Its name.
        type_: Its JSON type.
        optional: Whether it is optional.

    Returns:
        The parameter.
    """
    return {"name": name, "type": type_, "optional": optional, "rest": False}


def _signature(*parameters: Parameter) -> list[Signature]:
    """Build the signatures of a function with one, as script-signatures.js prints them.

    Args:
        *parameters: The parameters of its signature.

    Returns:
        The signatures.
    """
    return [{"parameters": list(parameters)}]


def test_render_stub_renames_parameters_python_cannot_name():
    """A parameter renamed from a non-identifier never takes another's name."""
    send = _signature(
        _param("$value", "str"), _param("arg0", "str"), _param("arg0_", "str")
    )
    assert _render_stub(Path("send.js"), ["send"], {"send": send}) == (
        "# Generated by Reflex from send.js; do not edit.\n" + IMPORTS + "\n"
        f"def send(arg0__: {STR}, arg0: {STR}, arg0_: {STR}, /) -> _EventSpec: ...\n"
    )


def test_render_stub_keeps_one_of_the_overloads_python_cannot_tell_apart():
    """Overloads with the same Python types are declared once, as a type checker rejects the second.

    Parameters are positional-only, so their names do not tell overloads apart:
    `when(value: Date)` and `when(pattern: RegExp)` are both a parameter of any
    type. The first is kept, as TypeScript tries overloads in order; a function
    left with one signature is not an overload.
    """
    when = (
        _signature(_param("value", "any"))
        + _signature(_param("pattern", "any"))
        + _signature(_param("count", "float"))
    )
    only = _signature(_param("value", "any")) + _signature(_param("pattern", "any"))
    assert _render_stub(
        Path("when.ts"), ["when", "only"], {"when": when, "only": only}
    ) == (
        "# Generated by Reflex from when.ts; do not edit.\n"
        "from builtins import float as _float\n"
        "from typing import Any as _Any, overload as _overload\n"
        "\n"
        "from reflex_base.event import EventSpec as _EventSpec\n"
        "from reflex_base.vars.base import Var as _Var\n"
        "\n"
        "@_overload\n"
        "def when(value: _Any, /) -> _EventSpec: ...\n"
        "@_overload\n"
        f"def when(count: {FLOAT}, /) -> _EventSpec: ...\n"
        "def only(value: _Any, /) -> _EventSpec: ...\n"
    )


