def test_render_stub_declares_the_importable_functions():
    """The stub declares each function Python can import; one with no signature takes any arguments.

    Python cannot import a keyword, a non-identifier, a special name or a name
    the stub uses for a type. An export named like a builtin type, such as
    ``str``, keeps the stub's annotations intact, since those use private
    aliases. TypeScript has no signature for a function of unknown type, and
    none at all when the types could not be read.
    """
    signatures = {
        "str": _signature(_param("value", "str")),
        "class": _signature(),
        "_str": _signature(),
        "__init__": _signature(),
        "constant": [],
    }
    functions = ["str", "class", "$private", "_str", "__init__", "unknown", "constant"]
    assert _render_stub(Path("m.js"), functions, signatures) == (
        "# Generated by Reflex from m.js; do not edit.\n" + IMPORTS + "\n"
        f"def str(value: {STR}, /) -> _EventSpec: ...\n"
        "def unknown(*args: _Any) -> _EventSpec: ...\n"
        "def constant(*args: _Any) -> _EventSpec: ...\n"
    )
    assert _render_stub(Path("party.ts"), ["go", "class"], {}) == (
        "# Generated by Reflex from party.ts; do not edit.\n"
        "from typing import Any as _Any\n"
        "\n"
        "from reflex_base.event import EventSpec as _EventSpec\n"
        "\n"
        "def go(*args: _Any) -> _EventSpec: ...\n"
    )
    assert _render_stub(Path("go.js"), ["go"], {"go": _signature()}) == (
        "# Generated by Reflex from go.js; do not edit.\n"
        "from reflex_base.event import EventSpec as _EventSpec\n"
        "\n"
        "def go() -> _EventSpec: ...\n"
    )
    # A module with no function to declare gets a stub with only its header.
    assert _render_stub(Path("empty.js"), [], {}) == (
        "# Generated by Reflex from empty.js; do not edit.\n"
    )


def test_renderer_digest():
    """The renderer's digest is that of the Reflex version, this module and script-signatures.js.

    The version stands in for Reflex's own frontend files, which a module's
    types can read through ``$/``.
    """
    assert (
        _renderer_digest()
        == hashlib.sha256(
            constants.Reflex.VERSION.encode()
            + b"\0"
            + Path(stubs.__file__).read_bytes()
            + (FRONTEND / "src" / "script-signatures.js").read_bytes()
        ).digest()
    )


def test_module_digest(tmp_path: Path):
    """The digest covers each file by its path and its bytes.

    A file listed twice counts once, a missing file by its path alone, and the
    renderer counts too.

    Args:
        tmp_path: pytest tmp_path fixture.
    """
    module = tmp_path / "party.js"
    module.write_text("export function go() {}\n")
    gone = tmp_path / "gone.d.ts"
    files = [str(module), str(gone), str(module)]
    expected = hashlib.sha256(_renderer_digest())
    expected.update(f"{gone}\1{module}\0".encode() + module.read_bytes() + b"\0")
    assert _module_digest(files) == expected.hexdigest()


def test_typescript_matches_the_frontend_package():
    """The typescript installed to read types is the one reflex-frontend uses."""
    dev_dependencies = json.loads((FRONTEND / "package.json").read_text())[
        "devDependencies"
    ]
    assert f"typescript@{dev_dependencies['typescript']}" == _TYPESCRIPT_PACKAGE
