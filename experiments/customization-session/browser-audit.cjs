 check('catalog reflow leaves persisted geometry unchanged',JSON.stringify(catalogGeometry)===JSON.stringify(initial));
 check('catalog renders actual XY and Community widgets',await page.locator('.catalog canvas').count()>0 && await page.locator('.catalog .ag-row').count()>0);
 const previewLegend=await page.locator('.catalog [data-xy-slot=legend]').boundingBox();
 const previewDay=await page.locator('.catalog [data-xy-slot=axis_title]').filter({hasText:'Day'}).boundingBox();
 check('catalog chart legend does not overlap axis title',previewLegend.y+previewLegend.height<previewDay.y);
 check('compact actual grid preview omits squeezed pagination',await page.locator('.catalog .ag-paging-panel:visible').count()===0);
 check('nonmodal catalog has no backdrop or dialog',await page.locator('[role=dialog],[aria-modal=true],[class*=backdrop]').count()===0);
 await page.screenshot({path:evidenceDir + '/edit-desktop-dock.png',fullPage:true});
 await page.getByRole('button',{name:'Close catalog',exact:true}).click();
 await page.locator('.catalog').waitFor({state:'detached'});
 await page.locator('[data-instance="accounts"] .ag-header-cell').filter({hasText:'Name'}).click();
 await page.locator('[data-instance="accounts"] .ag-header-cell').filter({hasText:'Name'}).click();
 await page.waitForFunction(()=>document.querySelector('[data-instance="accounts"] .ag-row')?.textContent.includes('Account 30'));
 await page.evaluate(()=>window.__gridIdentity=document.querySelector('[data-instance="accounts"] .ag-root'));
 const beforeMove=await engine();
